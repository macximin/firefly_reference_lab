function arcFor(sequence) {
  const found = arcRanges.find(([, start, end]) => sequence >= start && sequence <= end);
  if (!found) throw new Error(`no arc for ${sequence}`);
  return { id: found[0], start: found[1], end: found[2], name: found[3] };
}

function phaseFor(sequence, arc) {
  const length = arc.end - arc.start + 1;
  const ratio = (sequence - arc.start) / Math.max(1, length - 1);
  if (ratio < 0.22) return 'setup';
  if (ratio < 0.58) return 'escalation';
  if (ratio < 0.82) return 'turn';
  return 'payoff_bridge';
}

