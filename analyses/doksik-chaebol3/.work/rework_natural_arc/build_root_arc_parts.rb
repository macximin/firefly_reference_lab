def clean(value)
  value.to_s
       .gsub("**", "")
       .gsub(/`([^`]*)`/, '\\1')
       .gsub(/\s+/, " ")
       .strip
end

def sections(path)
  text = File.read(path)
  found = {}
  text.scan(/^##\s+((?:S4|N201|N401)-[^\s·]+).*?\n(.*?)(?=^##\s+|\z)/m) do |key, body|
    title = text.match(/^##\s+#{Regexp.escape(key)}\s*·\s*(.*?)\n/m)&.captures&.first.to_s
    fields = {}
    body.each_line do |line|
      next unless line.start_with?("-")
      normalized = line.sub(/\A-\s*/, "").gsub("**", "")
      label, value = normalized.split(":", 2)
      next unless value
      fields[clean(label)] = clean(value)
    end
    found[key] = { "title" => clean(title), "fields" => fields }
  end
  found
end

