def normalized_name(section)
  title = section.fetch("title")
  title = title.sub(/\A\d+~\d+회\s*·\s*/, "")
  title.sub(/\s*\[단계 B:.*\]\z/, "")
end

def regular_record(section, start_seq, end_seq)
  characters, locations, objects = actual_parts(section)
  start_scene = pick(section, "시작 장면")
  question = pick(section, "지배 질문")
  pressure = pick(section, "중간 압박")
  payment = pick(section, "구체 지급/미지급", "구체 지급 / 미지급")
  payoff, residual = paid_and_residual(payment)
  ending = pick(section, "끝 장면")
  boundary = pick(section, "다음 Arc 경계 신호")
  name = pick(section, "사건형 이름") rescue normalized_name(section)

  {
    "arc_id" => "ROOT-#{start_seq}",
    "arc_name" => name.sub(/[.]\z/, ""),
    "start_sequence" => start_seq.to_s,
    "end_sequence" => end_seq.to_s,
    "start_label" => start_seq.to_s,
    "end_label" => end_seq.to_s,
    "episode_count" => (end_seq - start_seq + 1).to_s,
    "main_characters" => characters,
    "main_locations" => locations,
    "concrete_premise" => [objects.empty? ? nil : objects.sub(/[.]\z/, ''), start_scene].compact.join(". "),
    "central_question" => question,
    "promise" => PROMISES.fetch(start_seq, "#{name.sub(/[.]\z/, '')}의 구체 결산을 지급한다."),
    "pressure_escalation" => pressure,
    "mid_turn" => MID_TURNS.fetch(start_seq),
    "concrete_payoff" => PAYOFFS.fetch(start_seq, payoff),
    "relationship_change" => RELATIONSHIPS.fetch(start_seq),
    "status_or_ability_change" => STATUS.fetch(start_seq),
    "residual_cost" => RESIDUALS.fetch(start_seq, residual),
    "next_arc_bridge" => ending,
    "boundary_signals" => boundary,
    "confidence" => "0.96"
  }
end

