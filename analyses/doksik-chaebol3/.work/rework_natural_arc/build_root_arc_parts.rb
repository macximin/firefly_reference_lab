def pick(section, *labels)
  labels.each do |label|
    value = section.fetch("fields")[label]
    return value if value && !value.empty?
  end
  raise "missing field #{labels.join('/')} in #{section.fetch('title')}"
end

def actual_parts(section)
  actual = pick(section, "실제 등장 인물·장소·물건", "인물·장소·물건")
  parts = actual.split(";").map(&:strip)
  characters = parts.shift.to_s
  locations = parts.shift.to_s
  objects = parts.join("; ")
  [characters, locations, objects]
end

def paid_and_residual(text)
  cues = [" 미지급", " 아직 ", " 남은 ", " 남는다", " 이월된다", " 끝나지", " 지급되지"]
  indexes = cues.map { |cue| text.index(cue) }.compact
  return [text, "후속 실행과 장기 유지 비용은 다음 Arc 이후에도 남는다."] if indexes.empty?

  cut = indexes.min
  paid = text[0...cut].sub(/[,.]\z/, "").strip
  residual = text[cut..].sub(/\A[,.\s]+/, "").strip
  residual = "#{residual}." unless residual.end_with?(".")
  [paid, residual]
end

