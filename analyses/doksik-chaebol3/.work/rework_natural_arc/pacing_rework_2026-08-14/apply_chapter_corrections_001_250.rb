rows = CSV.read(CHAPTER_MAP, headers: true)
by_sequence = rows.each_with_object({}) { |row, index| index[row["sequence"].to_i] = row }

missing = CORRECTIONS.keys.reject { |sequence| by_sequence.key?(sequence) }
abort("Missing chapter rows: #{missing.join(', ')}") unless missing.empty?

changed = []
CORRECTIONS.each do |sequence, fields|
  row = by_sequence.fetch(sequence)
  fields.each do |field, value|
    abort("Unknown field #{field.inspect} for sequence #{sequence}") unless rows.headers.include?(field)
    next if row[field] == value

    changed << [sequence, field, row[field], value]
    row[field] = value
  end
end

tmp_path = "#{CHAPTER_MAP}.pacing-rework.tmp"
CSV.open(tmp_path, "w", write_headers: true, headers: rows.headers) do |csv|
  rows.each { |row| csv << row }
end
FileUtils.mv(tmp_path, CHAPTER_MAP)

puts "corrected sequences=#{CORRECTIONS.length} fields=#{changed.length}"
changed.each { |sequence, field, _before, _after| puts "#{sequence}\t#{field}" }
